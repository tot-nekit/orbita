"""SQLite/SQLCipher connection boundary. Production never falls back to plaintext."""
import base64
import os
from pathlib import Path
from . import config


def production():
    return os.getenv('APP_ENV', 'local') == 'production'


def encryption_enabled():
    return os.getenv('DATABASE_ENCRYPTION', '1' if production() else '0') == '1'


if encryption_enabled():
    try:
        from sqlcipher3 import dbapi2 as sqlite3
    except ImportError:
        raise RuntimeError('Для шифрования установи зависимости из requirements.txt. Открытие без шифрования запрещено.') from None
else:
    import sqlite3


def key_bytes():
    value = os.getenv('DATABASE_KEY', '')
    if not value and os.getenv('DATABASE_KEY_FILE'):
        value = Path(os.environ['DATABASE_KEY_FILE']).read_text().strip()
    try:
        raw = base64.b64decode(value + '=' * (-len(value) % 4), altchars=b'-_', validate=True)
    except (ValueError, TypeError):
        raw = b''
    if len(raw) != 32:
        raise RuntimeError('DATABASE_KEY должен содержать 32 случайных байта в base64url. Ключ не выводится в журнал.')
    return raw


def configure_connection(db):
    """Key first, before any read. PRAGMA silently does nothing in stock SQLite."""
    if encryption_enabled():
        key = key_bytes().hex()  # Hex is strictly generated bytes, never interpolated input.
        db.execute('PRAGMA key = "x\'' + key + '\'"')
        version=db.execute('PRAGMA cipher_version').fetchone()
        if not version or not str(version[0]).startswith('4.'):
            db.close()
            raise RuntimeError('Драйвер базы не поддерживает SQLCipher. Открытие без шифрования запрещено.')
        db.execute('PRAGMA cipher_memory_security = ON')
        db.execute('PRAGMA temp_store = MEMORY')
    return db


def open_connection(path, readonly=False):
    path = Path(path).resolve()
    if not readonly:
        path.parent.mkdir(parents=True, exist_ok=True)
        # Create privately before SQLite opens the file; do not follow symlinks.
        if not path.exists():
            try:
                fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
                os.close(fd)
            except FileExistsError:
                pass
    db = sqlite3.connect(path.as_uri() + '?mode=ro', uri=True, timeout=60) if readonly else sqlite3.connect(str(path), timeout=60)
    try:
        configure_connection(db)
        db.row_factory = sqlite3.Row
        db.execute('SELECT count(*) FROM sqlite_master').fetchone()
        return db
    except Exception:
        db.close()
        raise


def validate_runtime():
    import ipaddress
    for value in os.getenv('TRUSTED_PROXY_CIDRS', '').split(','):
        if value.strip():ipaddress.ip_network(value.strip())
    if production():
        from urllib.parse import urlsplit
        url = urlsplit(os.getenv('PUBLIC_BASE_URL', ''))
        if url.scheme != 'https' or not url.hostname or url.path not in ('', '/') or url.username or url.password or url.query or url.fragment:
            raise RuntimeError('В production нужен PUBLIC_BASE_URL с HTTPS без пути, логина и параметров.')
        if os.getenv('AUTH_REQUIRED', '1') != '1' or not encryption_enabled() or os.getenv('COOKIE_SECURE') != '1':
            raise RuntimeError('Production требует регистрацию, шифрование базы и Secure cookies.')
        if len(os.getenv('APP_SESSION_SECRET', '')) < 32:
            raise RuntimeError('В production нужен постоянный APP_SESSION_SECRET длиной не менее 32 символов.')
    if encryption_enabled():
        key_bytes()
    if os.getenv('TELEGRAM_MODE','polling') not in ('polling','webhook'):
        raise RuntimeError('TELEGRAM_MODE должен быть polling или webhook.')
    if os.getenv('TELEGRAM_MODE')=='webhook' and os.getenv('TELEGRAM_BOT_TOKEN'):
        import re
        if not re.fullmatch(r'[A-Za-z0-9_-]{32,256}',os.getenv('TELEGRAM_WEBHOOK_SECRET','')):
            raise RuntimeError('В режиме webhook нужен отдельный TELEGRAM_WEBHOOK_SECRET.')
    if os.getenv('HOSTING_PROFILE')=='alwaysdata' and os.getenv('TELEGRAM_BOT_TOKEN') and os.getenv('TELEGRAM_MODE')!='webhook':
        raise RuntimeError('На alwaysdata Free используй webhook вместо постоянного polling.')
